function T_export = fET_InitialiseStatsTable(sessions)

% sessions = cellstr(sessions);
T_export = table(sessions,'VariableNames',{'session'});
newColsExp = {'Ntr_Test' 'Ntr_OptIn' ...
    'Ntr_Easy' 'Ntr_Medium' 'Ntr_Hard' 'Ntr_xHard' ...
    'Ntr_Corr' 'Ntr_Incorr' ...
    'accuracy' ...
    'nFixExpB' ...
    'nFixExpB_PriorCorr' 'nFixExpB_PriorIncorr' 'nFixExpB_Diff' ...
    'nSwitchExpB' ...
    'nSwitchExpB_PriorCorr' 'nSwitchExpB_PriorIncorr' 'nSwitchExpB_Diff' ...
    'decLat' ...
    'decLat_PriorCorr' 'decLat_PriorIncorr' 'decLat_Diff'};
for iLoop = 1:length(newColsExp)
    T_export.(newColsExp{iLoop}) = NaN(height(T_export), 1);
end

end